/**
 * Retired rule ids and the rule that absorbed each. Ids are never reused.
 * next.config.ts redirects their static pages; this also resolves the
 * homepage's `?rule=` deep links, hashes, search and stored history.
 * sys-12 was motion-3 filed twice. The others were merged by the November
 * 2026 council review (docs/research/rule-review/council.md).
 */
export const ruleAliases: Record<string, string> = {
  "sys-12": "motion-3",
  "motion-5": "motion-4",
  "motion-22": "motion-21",
  "motion-23": "motion-14",
  "motion-25": "motion-6",
  "motion-26": "motion-24",
  "motion-27": "motion-7",
  "sys-14": "motion-14",
  "color-2": "sys-5",
  "color-3": "color-12",
  "color-5": "color-6",
  "layout-8": "layout-3",
};

export function resolveRuleId(id: string | null): string | null {
  // Own keys only. `?rule=valueOf` would otherwise read Object.prototype and
  // hand useState a function, which it calls and crashes on.
  if (id === null || !Object.hasOwn(ruleAliases, id)) return id;
  return ruleAliases[id];
}
